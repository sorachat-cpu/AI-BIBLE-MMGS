export function getTopic(id) {
  const topic = TOPICS.find((t) => t.id === id);
  if (!topic) throw new Error(`ไม่รู้จักหัวข้อ "${id}" -- มี: ${TOPICS.map((t) => t.id).join(", ")}`);
  return topic;
}

/**
 * Rotate through topics by how long ago each was used, so the page does not repeat one
 * while five others sit unused. `usage` maps topic id -> ISO date last posted.
 */
export function pickTopic(usage = {}, { excludeIds = [] } = {}) {
  const pool = TOPICS.filter((t) => !excludeIds.includes(t.id));
  if (!pool.length) return null;
  return pool.sort((a, b) => (usage[a.id] ?? "").localeCompare(usage[b.id] ?? ""))[0];
}
